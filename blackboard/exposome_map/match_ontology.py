#!/usr/bin/env python3
"""Look up the labels of the map nodes on ExpoPortal and save the matches.

    python match_ontology.py                     # reads exposome_map.ttl, updates exposome_map_mappings.ttl
    python match_ontology.py --structures-only   # only looks up the chemical structures again

Every label of a node (rdfs:label, skos:altLabel, skos:hiddenLabel) is compared,
ignoring case, with the labels and exact synonyms of all ontology terms on
ExpoPortal. The lookup uses the public SPARQL endpoint, the same backend as the
ExpoPortal MCP server. These matches (em:labelMatch) are automatic and not curated.

The mappings file has two parts, divided by a marker line:

  above   what curators wrote by hand: em:curatorMatch (this term is right for
          the node) and em:curatorNoMatch (this term is wrong for the node).
          This part is kept exactly as it is, comments included.
  below   the label matches, written again on every run. A term that a curator
          rejected for a node (em:curatorNoMatch) is not added to that node.

Chemical structures: every ChEBI term that is a curator match or a label match
gets its SMILES from Wikidata (em:smiles), found by its ChEBI identifier. The
isomeric SMILES is used when Wikidata has one, the canonical SMILES otherwise.
A SMILES written by hand above the marker line is used instead. The structures
are at the end of the part below the marker; --structures-only writes only them
again and leaves the label matches as they are.

The script stops without writing when a curator statement is below the marker
line, because it would be lost. Ontology terms that are only used in curator matches
get their label and ontologies from ExpoPortal, in the part below the marker,
unless the part above already gives them.

Requires rdflib (Debian: python3-rdflib). Run build_map.py afterwards.
"""
import argparse
import datetime
import json
import os
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from rdflib import Graph, Namespace, RDFS, URIRef
from rdflib.namespace import SKOS

ENDPOINT = "https://sparql.expoportal.biohackeu.bigcat-bioinformatics.org/sparql"
EM = Namespace("https://example.org/exposome-map/")
BATCH = 30
MARKER = "# ==== generated by match_ontology.py: do not edit below this line ===="
MARKER_START = "# ==== generated by match_ontology.py"
STRUCT_MARKER = "# ---- chemical structures, generated by match_ontology.py ----"
WIKIDATA = "https://query.wikidata.org/sparql"
CHEBI = "http://purl.obolibrary.org/obo/CHEBI_"
CURATOR_PREDS = (EM.curatorMatch, EM.curatorNoMatch)
DEFAULT_HEAD = """\
@prefix em:   <https://example.org/exposome-map/> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .

# =====================================================================
#  Curator matches -- written by hand
#
#  Everything above the line "generated by match_ontology.py" is kept
#  exactly as it is when the label matches are looked up again
#  ("make match"). Put every em:curatorMatch and em:curatorNoMatch here,
#  with anything that belongs to it: comments, extra prefixes, who made
#  the match, a label for the term.
#
#  em:curatorMatch     this term is right for the node. Example:
#    em:chem_ozone em:curatorMatch <http://purl.obolibrary.org/obo/CHEBI_25812> .
#
#  em:curatorNoMatch   this term is wrong for the node. It overrules a
#                      label match with the same term, and "make match"
#                      does not add that label match again. Example:
#    em:mod_age em:curatorNoMatch <http://purl.obolibrary.org/obo/PR_000013884> .
#
#  The label and the ontologies of a term are looked up on ExpoPortal by
#  "make match", so they do not have to be written here.
# =====================================================================

"""
LABEL_PREDS = (
    "<http://www.w3.org/2000/01/rdf-schema#label>",
    "<http://www.w3.org/2004/02/skos/core#prefLabel>",
    "<http://www.w3.org/2004/02/skos/core#altLabel>",
    "<http://www.geneontology.org/formats/oboInOwl#hasExactSynonym>",
)


def lookup(terms):
    """Return {lowercase term: {iri: [label, set(acronyms)]}} for one batch."""
    values = ", ".join('"%s"' % t.replace("\\", "\\\\").replace('"', '\\"') for t in terms)
    q = f"""
SELECT ?key ?g ?s ?l WHERE {{
  VALUES ?p {{ {' '.join(LABEL_PREDS)} }}
  GRAPH ?g {{
    ?s ?p ?l .
    FILTER(isLiteral(?l))
    BIND(LCASE(STR(?l)) AS ?key)
    FILTER(?key IN ({values}))
  }}
  FILTER(STRSTARTS(STR(?g), "http://data.bioontology.org/ontologies/"))
}}"""
    rows = sparql(q)
    out = {}
    for b in rows:
        if b["s"]["type"] != "uri":
            continue
        acr = b["g"]["value"].split("/ontologies/")[1].split("/")[0]
        entry = out.setdefault(b["key"]["value"], {}).setdefault(b["s"]["value"], [b["l"]["value"], set()])
        entry[1].add(acr)
    return out


def sparql(q, endpoint=ENDPOINT):
    req = urllib.request.Request(
        endpoint, data=urllib.parse.urlencode({"query": q}).encode(),
        headers={"Accept": "application/sparql-results+json", "User-Agent": "exposome-map-term-lookup"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return json.load(r)["results"]["bindings"]


def describe(iris):
    """Return {iri: [label or None, set(acronyms)]} for one batch of ontology terms."""
    q = f"""
SELECT ?g ?s ?p ?l WHERE {{
  VALUES ?s {{ {' '.join('<%s>' % i for i in iris)} }}
  VALUES ?p {{ {' '.join(LABEL_PREDS[:2])} }}
  GRAPH ?g {{ ?s ?p ?l . FILTER(isLiteral(?l)) }}
  FILTER(STRSTARTS(STR(?g), "http://data.bioontology.org/ontologies/"))
}}"""
    out, labels = {}, {}
    for b in sparql(q):
        iri = b["s"]["value"]
        out.setdefault(iri, [None, set()])[1].add(b["g"]["value"].split("/ontologies/")[1].split("/")[0])
        # rdfs:label before skos:prefLabel, English or no language before other languages
        rank = (b["l"].get("xml:lang", "") not in ("", "en"), LABEL_PREDS.index("<%s>" % b["p"]["value"]),
                b["l"]["value"])
        labels.setdefault(iri, []).append(rank)
    for iri, ranks in labels.items():
        out[iri][0] = min(ranks)[2]
    return out


def smiles(iris):
    """Return {ChEBI term IRI: (SMILES, Wikidata item IRI)} for the terms that Wikidata knows."""
    ids = sorted(i[len(CHEBI):] for i in iris)
    q = f"""
PREFIX wdt: <http://www.wikidata.org/prop/direct/>
SELECT ?id ?item ?isomeric ?canonical WHERE {{
  VALUES ?id {{ {' '.join('"%s"' % i for i in ids)} }}
  ?item wdt:P683 ?id .
  OPTIONAL {{ ?item wdt:P2017 ?isomeric }}
  OPTIONAL {{ ?item wdt:P233 ?canonical }}
}}"""
    choices = {}
    for b in sparql(q, WIKIDATA):
        for rank, key in enumerate(("isomeric", "canonical")):      # isomeric before canonical
            if key in b:
                choices.setdefault(CHEBI + b["id"]["value"], []).append((rank, b[key]["value"], b["item"]["value"]))
    return {iri: min(c)[1:] for iri, c in choices.items()}


def structure_lines(chebi, kept):
    """The Turtle lines with the SMILES of the ChEBI terms, for the end of the file."""
    out = [
        STRUCT_MARKER,
        "# SMILES of the ChEBI terms above, for the 2D structures in the web page.",
        f"# Source: {WIKIDATA} (isomeric SMILES, P2017, if there is one; else canonical SMILES, P233)",
        f"# Date:   {datetime.date.today().isoformat()}",
        "",
    ]
    todo = sorted(i for i in chebi if (URIRef(i), EM.smiles, None) not in kept)   # not the ones given by hand
    found = smiles(todo) if todo else {}
    for iri in todo:
        if iri in found:
            out.append(f"<{iri}> em:smiles {ttl_string(found[iri][0])} ;")
            out.append(f"    rdfs:seeAlso <{found[iri][1]}> .")
        else:
            print(f"warning: no SMILES on Wikidata for <{iri}>", file=sys.stderr)
    print(f"{len(found)} of {len(chebi)} ChEBI terms have a SMILES from Wikidata, "
          f"{len(chebi) - len(todo)} have one written by hand", file=sys.stderr)
    return out


def write_mappings(dest, head, lines, kept):
    text = head + "\n".join(lines) + "\n"
    new = Graph().parse(data=text, format="turtle")       # make sure the output is valid Turtle
    assert all(t in new for t in kept), "the part written by hand is not complete in the new file"
    tmp = dest.with_name(dest.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, dest)                                 # the old file stays whole if anything fails before this


def ttl_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def split_mappings(dest):
    """Return (head, rest) of the mappings file: the text above the marker line, kept as it
    is, and the text from the marker line on, which is written again."""
    if not dest.exists():
        return DEFAULT_HEAD, ""
    text = dest.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith(MARKER_START):
            return "".join(lines[:i]), "".join(lines[i:])
    # A file from before the marker line existed. It was generated as a whole, unless
    # somebody added to it: a curator match, or lines above the "Generated by" comment.
    top = []
    for line in lines:
        if line.startswith("# Generated by match_ontology.py"):
            break
        top.append(line)
    by_hand = [l for l in top if l.strip() and not l.startswith("@prefix")]
    legacy = Graph().parse(data=text, format="turtle")
    if by_hand or any((None, p, None) in legacy for p in CURATOR_PREDS):
        sys.exit(f"{dest} has no marker line, and it seems to have lines written by hand, so it is not "
                 f"clear what must be kept; nothing was changed.\nAdd this line below the part that "
                 f"must be kept, and run again:\n{MARKER}")
    return DEFAULT_HEAD, text


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("ttl", nargs="?", default=here / "exposome_map.ttl", type=Path)
    ap.add_argument("--max-per-node", type=int, default=8,
                    help="most label matches kept per node (terms found in most ontologies first)")
    ap.add_argument("--structures-only", action="store_true",
                    help="only look up the chemical structures again; the label matches stay as they are")
    args = ap.parse_args()
    dest = args.ttl.with_name(args.ttl.stem + "_mappings.ttl")

    # ---- what was written by hand: read it before anything else, and stop if some of it would be lost
    head, rest = split_mappings(dest)
    if head and not head.endswith("\n"):
        head += "\n"
    try:
        kept = Graph().parse(data=head, format="turtle")
    except Exception as e:
        sys.exit(f"The part of {dest} above the marker line is not valid Turtle; nothing was changed.\n{e}")
    if rest:
        try:
            old = Graph().parse(data=head + rest, format="turtle")
        except Exception as e:
            sys.exit(f"{dest} is not valid Turtle; nothing was changed.\n{e}")
        lost = sorted(t for p in CURATOR_PREDS for t in old.triples((None, p, None)) if t not in kept)
        if lost:
            sys.exit(f"{len(lost)} curator statement(s) in {dest} are below the marker line and would be lost; "
                     "nothing was changed.\nMove them above the marker line and run again:\n"
                     + "\n".join(f"  <{s}> em:{str(p).rsplit('/', 1)[-1]} <{o}> ." for s, p, o in lost))
    curated = sorted(set(kept.subject_objects(EM.curatorMatch)))
    rejected = set(kept.subject_objects(EM.curatorNoMatch))
    for n, o in sorted(rejected & set(curated)):
        print(f"warning: <{o}> is both a curator match and a curator no match of <{n}>", file=sys.stderr)

    if args.structures_only:
        if not rest.startswith(MARKER_START):
            sys.exit(f"{dest} has no label matches yet; run the full lookup first.")
        labels = rest.split(STRUCT_MARKER)[0].rstrip("\n")
        matched = set(old.objects(None, EM.labelMatch)) | {o for _, o in curated}
        chebi = {str(o) for o in matched if str(o).startswith(CHEBI)}
        write_mappings(dest, head, [labels, ""] + structure_lines(chebi, kept), kept)
        print(f"wrote {dest}", file=sys.stderr)
        return

    g = Graph().parse(args.ttl, format="turtle")
    node_terms = {}
    for n in sorted(set(g.subjects(EM.ink, None))):
        labels = [str(l) for p in (RDFS.label, SKOS.altLabel, SKOS.hiddenLabel) for l in g.objects(n, p)]
        node_terms[n] = sorted({l.lower() for l in labels})
    for n in sorted({n for n, _ in set(curated) | rejected} - set(node_terms)):
        print(f"warning: curator statement on <{n}>, which is not a node of the map", file=sys.stderr)
    unique = sorted({t for ts in node_terms.values() for t in ts})
    print(f"{len(node_terms)} nodes, {len(unique)} labels; querying {ENDPOINT}", file=sys.stderr)

    found = {}
    for i in range(0, len(unique), BATCH):
        found.update(lookup(unique[i:i + BATCH]))
        print(f"  {min(i + BATCH, len(unique))}/{len(unique)}", file=sys.stderr)

    out = [
        MARKER,
        "@prefix em:   <https://example.org/exposome-map/> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "",
        "# Label matches, generated by match_ontology.py.",
        f"# Source: {ENDPOINT}",
        f"# Date:   {datetime.date.today().isoformat()}",
        "# Automatic matches on label (ignoring case); not curated.",
        "",
    ]
    terms_seen, n_nodes, n_links, n_rejected = {}, 0, 0, 0
    for n, terms in node_terms.items():
        hits = {}
        for t in terms:
            for iri, (label, acrs) in found.get(t, {}).items():
                if (n, URIRef(iri)) in rejected:          # a curator said no: never a label match
                    continue
                h = hits.setdefault(iri, [label, set()])
                h[1] |= acrs
        n_rejected += sum(1 for m, o in rejected if m == n and any(str(o) in found.get(t, {}) for t in terms))
        if not hits:
            continue
        ranked = sorted(hits.items(), key=lambda kv: (-len(kv[1][1]), kv[0]))[:args.max_per_node]
        n_nodes += 1
        n_links += len(ranked)
        out.append(f"em:{str(n).rsplit('/', 1)[-1]} em:labelMatch")
        out.append(" ,\n".join(f"    <{iri}>" for iri, _ in ranked) + " .")
        for iri, (label, acrs) in ranked:
            t = terms_seen.setdefault(iri, [label, set()])
            t[1] |= acrs

    # ---- label and ontologies of the terms that are only used in curator matches
    extra = sorted({str(o) for _, o in curated} - set(terms_seen))
    for i in range(0, len(extra), BATCH):
        for iri, (label, acrs) in describe(extra[i:i + BATCH]).items():
            terms_seen[iri] = [label, acrs]
    for iri in extra:
        if iri not in terms_seen:
            print(f"warning: curator match <{iri}> was not found on ExpoPortal", file=sys.stderr)

    # What the part written by hand says about a term is not said again here.
    out.append("")
    for iri, (label, acrs) in sorted(terms_seen.items()):
        term = URIRef(iri)
        parts = []
        if label is not None and (term, RDFS.label, None) not in kept:
            parts.append("rdfs:label " + ttl_string(label))
        if acrs and (term, EM.inOntology, None) not in kept:
            parts.append("em:inOntology " + " , ".join(ttl_string(a) for a in sorted(acrs)))
        if parts:
            out.append(f"<{iri}> " + " ;\n    ".join(parts) + " .")

    chebi = {i for i in set(terms_seen) | {str(o) for _, o in curated} if i.startswith(CHEBI)}
    write_mappings(dest, head, out + [""] + structure_lines(chebi, kept), kept)
    print(f"{n_nodes} of {len(node_terms)} nodes matched, {n_links} label matches, "
          f"{len(curated)} curator matches and {len(rejected)} curator no matches kept "
          f"({n_rejected} label matches left out), {len(terms_seen)} ontology terms; wrote {dest}", file=sys.stderr)


if __name__ == "__main__":
    main()
